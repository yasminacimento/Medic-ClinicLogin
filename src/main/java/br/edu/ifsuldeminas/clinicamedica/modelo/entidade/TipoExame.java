package br.edu.ifsuldeminas.clinicamedica.modelo.entidade;

/**
 *
 * @author Alexandre
 */
public class TipoExame {

    private Integer idTipoExame;
    private String nome;
    private String descricao;
    private Double valor;
    private Integer funcionarioId;
    private Integer consultorioId;

    // Relacionamentos
    private Funcionario funcionario = new Funcionario();
    private Consultorio consultorio = new Consultorio();

    public TipoExame() {}

    public Integer getIdTipoExame() {
        return idTipoExame;
    }

    public void setIdTipoExame(Integer idTipoExame) {
        this.idTipoExame = idTipoExame;
    }

    public String getNome() {
        return nome;
    }

    public void setNome(String nome) {
        this.nome = nome;
    }

    public String getDescricao() {
        return descricao;
    }

    public void setDescricao(String descricao) {
        this.descricao = descricao;
    }

    public Double getValor() {
        return valor;
    }

    public void setValor(Double valor) {
        this.valor = valor;
    }

    public Integer getFuncionarioId() {
        return funcionarioId;
    }

    public void setFuncionarioId(Integer funcionarioId) {
        this.funcionarioId = funcionarioId;
    }

    public Integer getConsultorioId() {
        return consultorioId;
    }

    public void setConsultorioId(Integer consultorioId) {
        this.consultorioId = consultorioId;
    }

    public Funcionario getFuncionario() {
        return funcionario;
    }

    public void setFuncionario(Funcionario funcionario) {
        this.funcionario = funcionario;
    }

    public Consultorio getConsultorio() {
        return consultorio;
    }

    public void setConsultorio(Consultorio consultorio) {
        this.consultorio = consultorio;
    }
}